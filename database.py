"""Postgres persistence for the existing server-side workflows."""
from contextlib import contextmanager

LOCK = "select pg_advisory_xact_lock(1740186001)"


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def row_factory(cursor):
    names = [column.name for column in cursor.description or ()]
    return lambda values: Row(zip(names, values))


def connect(url):
    import psycopg

    config = psycopg.conninfo.conninfo_to_dict(url)
    config.setdefault("sslmode", "require")
    config.setdefault("connect_timeout", "10")
    db = psycopg.connect(**config, row_factory=row_factory)
    try:
        db.execute("set search_path to loa_fire, pg_catalog")
        db.commit()
    except BaseException:
        db.close()
        raise
    return db


def initialize(url, sqlite_schema):
    # Keep the same columns and foreign keys across both backends.
    schema = (sqlite_schema.replace("integer primary key", "bigint generated by default as identity primary key")
              .replace("integer references", "bigint references")
              .replace("owner integer", "owner bigint")
              .replace("text unique collate nocase", "citext unique")
              .replace("text collate nocase", "citext")
              .replace("expires real", "expires double precision")
              .replace("bytes blob", "bytes bytea"))
    with connect(url) as db:
        db.execute(LOCK)
        db.execute("create schema if not exists loa_fire")
        db.execute("revoke all on schema loa_fire from public")
        db.execute("create extension if not exists citext with schema loa_fire")
        extension_schema = db.execute(
            "select n.nspname from pg_extension e join pg_namespace n on n.oid=e.extnamespace where e.extname='citext'"
        ).fetchone()[0]
        from psycopg import sql

        schema = sql.SQL(schema.replace("citext", "{}.citext"))
        for statement in schema.format(*([sql.Identifier(extension_schema)] * 2)).as_string(db).split(";"):
            if statement.strip():
                db.execute(statement)


class Database:
    def __init__(self, connection, postgres):
        self.connection = connection
        self.postgres = postgres

    def execute(self, query, params=()):
        if self.postgres:
            query = query.replace("?", "%s")
        return self.connection.execute(query, params)

    def begin_write(self):
        self.execute(LOCK if self.postgres else "begin immediate")

    def insert_record(self, params):
        query = "insert into records(module,asset,ident,data,review,created) values(?,?,?,?,?,?)"
        if self.postgres:
            return self.execute(query + " returning id", params).fetchone()[0]
        return self.execute(query, params).lastrowid

    def commit(self):
        self.connection.commit()

    @contextmanager
    def transaction(self):
        try:
            yield self
        finally:
            # Writes explicitly commit before sending a successful response.
            self.connection.close()

def migrate_sqlite(url, source_path):
    """Copy a consistent local snapshot into a fresh Postgres database."""
    import sqlite3
    from contextlib import closing
    from psycopg import sql

    tables = ("users", "records", "files", "audit")
    with closing(sqlite3.connect(source_path.as_uri() + "?mode=ro", uri=True)) as source:
        with connect(url) as target:
            source.execute("begin")
            target.execute(LOCK)
            for table in (*tables, "sessions", "batches"):
                query = sql.SQL("select 1 from {} limit 1").format(sql.Identifier(table))
                if target.execute(query).fetchone():
                    raise ValueError("Supabase already contains application data. Migration stopped.")

            counts = {}
            for table in tables:
                table_name = sql.Identifier(table)
                rows = source.execute(f"select * from {table} order by id")
                columns = [column[0] for column in rows.description]
                query = sql.SQL("insert into {} ({}) values ({})").format(
                    table_name,
                    sql.SQL(", ").join(map(sql.Identifier, columns)),
                    sql.SQL(", ").join(sql.Placeholder() for _ in columns),
                )
                count = 0
                linked_records = []
                asset_index = columns.index("asset") if table == "records" else None
                for row in rows:
                    if asset_index is not None and row[asset_index] is not None:
                        linked_records.append((row[asset_index], row[0]))
                        row = (*row[:asset_index], None, *row[asset_index + 1:])
                    target.execute(query, row)
                    count += 1

                for asset, record_id in linked_records:
                    target.execute("update records set asset=%s where id=%s", (asset, record_id))

                sequence = sql.SQL(
                    "alter table {} alter column id restart with {}"
                ).format(table_name, sql.Literal(target.execute(
                    sql.SQL("select greatest(coalesce(max(id), 0), 0) + 1 from {}").format(table_name)
                ).fetchone()[0]))
                target.execute(sequence)
                counts[table] = count
            return counts
